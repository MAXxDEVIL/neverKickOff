"""Generate tests/fixtures/contract.json from the Python implementation.

The Python version is the source of truth, so this records what Python actually
does rather than what we assume it does. Rust and Java then have to reproduce
the same file. Re-run after any deliberate Python change:

    .venv/bin/python tests/gen_fixtures.py

Only deterministic behaviour goes in here: pure functions, and engine runs that
finish on their own (repeat=N) with jitter=0. Anything that depends on wall-clock
timing stays as a per-language test instead.
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from engine import Engine, normalize_steps  # noqa: E402
from hotkeys import format_hotkey  # noqa: E402
from main import load_spec, parse_combo  # noqa: E402
from test_engine import FakeDevice  # noqa: E402
from window import _as_text  # noqa: E402
import ydotool  # noqa: E402


def token(key):
    """pynput Key/KeyCode -> the neutral form Rust and Java can also produce."""
    name = getattr(key, "name", None)
    if name is not None:
        return {"kind": "named", "name": name}
    return {"kind": "char", "char": getattr(key, "char", "")}


def token_str(key):
    """The string an engine fixture records when it hands a key to the device."""
    name = getattr(key, "name", None)
    return name if name is not None else getattr(key, "char", "")


def attempt(fn, *args):
    """Run fn, returning (value, exception-or-None)."""
    try:
        return fn(*args), None
    except Exception as exc:
        return None, exc


def message(exc):
    """The message a caller sees, without Python's KeyError repr wrapping."""
    args = getattr(exc, "args", ())
    if len(args) == 1 and isinstance(args[0], str):
        return args[0]
    return str(exc)


def spec_input(spec):
    """Engine fixtures use plain string keys so the token is language-neutral."""
    return spec


def _tag_token(name):
    """A bare key name -> the neutral tagged form ('c' is a char, the rest named)."""
    if len(name) > 1:
        return {"kind": "named", "name": name}
    return {"kind": "char", "char": name}


def _tag_keys(spec):
    """Rewrite every "keys" list to the tagged form the engine fixtures use."""
    spec = dict(spec)
    if isinstance(spec.get("keys"), list):
        spec["keys"] = [_tag_token(k) for k in spec["keys"]]
    if isinstance(spec.get("steps"), list):
        spec["steps"] = [_tag_keys(step) for step in spec["steps"]]
    return spec


def _token_of(arg):
    """The string a fixture records for whatever the engine handed the device."""
    if isinstance(arg, dict):
        return arg.get("name") if arg.get("kind") == "named" else arg.get("char")
    return str(arg)


def build():
    out = {
        "note": "Generated by tests/gen_fixtures.py. Do not edit by hand.",
        "normalize_steps": [],
        "parse_combo": [],
        "load_spec": [],
        "format_hotkey": [],
        "as_text": [],
        "keycode": [],
        "engine": [],
    }

    flat_specs = [
        {"action": "keys", "keys": ["ctrl"], "hold": 0.5},
        {"action": "mouse", "button": "right"},
        {},
        {"steps": [{"action": "mouse", "button": "middle"}]},
        {"action": "keys", "keys": []},
    ]
    for spec in flat_specs:
        out["normalize_steps"].append({"spec": spec, "expect": normalize_steps(spec)})

    combos = [
        "ctrl+alt+c", ["ctrl", "c"], "<ctrl>+<alt>+s", "escape", "a",
        "F6", "ctrl+nosuchkey", "win+r", "pgup", "control+shift+q", "",
    ]
    for combo in combos:
        value, err = attempt(parse_combo, combo)
        out["parse_combo"].append({
            "combo": combo,
            "expect": [token(k) for k in value] if value is not None else None,
            "error": message(err) if err else None,
        })

    clicks = [
        {"steps": [{"action": "keys", "keys": "ctrl+c"},
                   {"action": "mouse", "button": "left"}]},
        {"action": "keys", "keys": "ctrl+c"},
        {"action": "mouse", "button": "left"},
        {"steps": [{"action": "mouse", "button": "left"}]},
    ]
    for click in clicks:
        value, err = attempt(load_spec, click)
        out["load_spec"].append({
            "click": click,
            "expect": _spec_tokens(value) if value is not None else None,
            "error": message(err) if err else None,
        })

    hotkey_cases = [
        ("s", 0x0004 | 0x0008), ("F6", 0), ("Escape", 0), ("S", 0x0001),
        ("Control_L", 0x0004), ("Return", 0), ("a", 0), ("t", 0x0001 | 0x0004),
        ("F12", 0x0040), ("space", 0), ("control_l", 0x0008),
    ]
    for keysym, state in hotkey_cases:
        out["format_hotkey"].append({
            "keysym": keysym, "state": state,
            "expect": format_hotkey(keysym, state),
        })

    as_text_cases = [
        {"kind": "bytes", "data": list(b"VRStream")},
        {"kind": "str", "data": "Notepad"},
        {"kind": "bytes", "data": []},
        {"kind": "null"},
        {"kind": "bytes", "data": list("é".encode("utf-8"))},
        {"kind": "str", "data": ""},
    ]
    for case in as_text_cases:
        if case["kind"] == "bytes":
            value = bytes(case["data"])
        elif case["kind"] == "str":
            value = case["data"]
        else:
            value = None
        out["as_text"].append({"value": case, "expect": _as_text(value)})

    key_cases = [
        {"kind": "named", "name": "ctrl"}, {"kind": "named", "name": "enter"},
        {"kind": "named", "name": "alt"}, {"kind": "named", "name": "f1"},
        {"kind": "named", "name": "cmd"}, {"kind": "named", "name": "space"},
        {"kind": "named", "name": "esc"}, {"kind": "named", "name": "f20"},
        {"kind": "named", "name": "media_volume_up"},
        {"kind": "char", "char": "c"}, {"kind": "char", "char": "1"},
        {"kind": "char", "char": "-"}, {"kind": "char", "char": "!"},
        {"kind": "char", "char": "z"}, {"kind": "char", "char": "0"},
        {"kind": "char", "char": "/"},
    ]
    for case in key_cases:
        key = _pynput_key(case)
        value, err = attempt(ydotool.keycode, key)
        # The ValueError text embeds a pynput repr, which has no meaning outside
        # Python, so only the exception kind is part of the contract.
        out["keycode"].append({
            "key": case,
            "expect": value,
            "error_kind": type(err).__name__ if err else None,
        })

    engine_cases = [
        ({"action": "mouse", "button": "left", "interval": 0.001, "repeat": 5}, None, None),
        ({"action": "keys", "keys": ["ctrl", "c"], "interval": 0.001, "repeat": 2}, None, None),
        ({"interval": 0.001, "repeat": 2, "steps": [
            {"action": "keys", "keys": ["ctrl", "c"], "count": 1, "hold": 0.0, "wait": 0.0},
            {"action": "mouse", "button": "left", "count": 1, "hold": 0.0, "wait": 0.0}]}, None, None),
        ({"interval": 0.001, "repeat": 1, "steps": [
            {"action": "mouse", "button": "left", "count": 3, "hold": 0.0, "wait": 0.0}]}, None, None),
        ({"action": "mouse", "button": "left", "interval": 0.001, "repeat": 0}, None, None),
        ({"action": "mouse", "interval": 0.001, "repeat": 3, "window": "notepad"},
         "notes.txt - Notepad", None),
        ({"interval": 0.001, "repeat": 1, "steps": [
            {"action": "mouse", "button": "left", "count": 1, "hold": 0.0, "wait": 0.0},
            {"action": "mouse", "button": "right", "count": 1, "hold": 0.0, "wait": 0.0}]}, None, None),
        ({"action": "keys", "keys": ["ctrl", "c"], "interval": 0.001, "repeat": 1},
         None, 2),
        # Duration and jitter cases are deliberately absent: their tick count
        # depends on wall-clock timing, so they are per-language tests rather
        # than a byte-exact cross-language contract.
    ]
    for spec, focused, fail_on in engine_cases:
        out["engine"].append(_engine_case(spec, focused, fail_on))

    return out


def _spec_tokens(spec):
    """Replace populated "keys" lists with neutral tokens, keeping order."""
    out = {}
    for key, value in spec.items():
        if key == "keys":
            out[key] = [token(k) for k in value]
        elif key == "steps":
            out[key] = [_spec_tokens(step) for step in value]
        else:
            out[key] = value
    return out


def _pynput_key(case):
    from pynput.keyboard import Key, KeyCode
    if case["kind"] == "named":
        return getattr(Key, case["name"])
    return KeyCode.from_char(case["char"])


class _Recorder(FakeDevice):
    def __init__(self, fail_on=None):
        super().__init__()
        self.fail_on = fail_on
        self._presses = 0

    def key_press(self, key):
        if self.fail_on is not None:
            self._presses += 1
            if self._presses == self.fail_on:
                raise RuntimeError("device failure")
        super().key_press(key)


def _engine_case(spec, focused, fail_on):
    spec = _tag_keys(spec)
    device = _Recorder(fail_on)
    engine = Engine(device, focused_window=(lambda: focused) if focused else None)
    fired, err = attempt(engine.run, spec)
    return {
        "spec": spec,
        "focused": focused,
        "fail_on": fail_on,
        "expect_fired": fired,
        "expect_events": [[kind, _token_of(arg)] for _, kind, arg in device.events],
        "expect_error_kind": type(err).__name__ if err else None,
    }


if __name__ == "__main__":
    target = Path(__file__).with_name("fixtures") / "contract.json"
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(json.dumps(build(), indent=2, sort_keys=False) + "\n")
    print(f"wrote {target}")
